CREATE DATABASE IF NOT EXISTS fee_db; USE fee_db;
CREATE TABLE student(id BIGINT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100),email VARCHAR(100),course VARCHAR(100),total_fee DECIMAL(12,2));
CREATE TABLE payment(id BIGINT AUTO_INCREMENT PRIMARY KEY,student_id BIGINT,amount DECIMAL(12,2),method VARCHAR(30),paid_on DATE,
 FOREIGN KEY(student_id) REFERENCES student(id) ON DELETE CASCADE);
