CREATE DATABASE IF NOT EXISTS fee_db; USE fee_db;
CREATE TABLE course(id BIGINT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) UNIQUE NOT NULL,fee DECIMAL(12,2) NOT NULL CHECK(fee>0));
CREATE TABLE student(id BIGINT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL,phone VARCHAR(20),email VARCHAR(100),
 course VARCHAR(100),course_id BIGINT,total_fee DECIMAL(12,2) NOT NULL,discount DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK(discount>=0),
 FOREIGN KEY(course_id) REFERENCES course(id));
CREATE TABLE payment(id BIGINT AUTO_INCREMENT PRIMARY KEY,student_id BIGINT NOT NULL,amount DECIMAL(12,2) NOT NULL CHECK(amount>0),
 method VARCHAR(30),reference VARCHAR(60),paid_on DATE,FOREIGN KEY(student_id) REFERENCES student(id) ON DELETE CASCADE);
